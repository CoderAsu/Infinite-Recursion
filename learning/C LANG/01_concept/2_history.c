/*
    Algorithmic Language
    -> ALGOL is the root of all modern languages.
    -> Introduced the concept of block structure.
    -> Developed in 1958.

    Limitations:
    -> Limited data types.
    -> Lack of input/output facilities.
    -> Lack of practical features for system programming.
    -> Less suitable for general-purpose programming.
*/



/*
    Combined Programming Language
    -> CPL is a multi-purpose programming language.
    -> Developed in 1963.
    -> Has richer set of data types, I/O facilities, and support for system programming.

    Limitations:
    -> Complex and inefficient to implement on the limited hardware.
    -> Difficult to write compilers for CPL.

*/

/*
    Basic CPL
    -> BCPL is the simplified version of CPL.
    -> Developed in mid-1960s by Martin Richards.
    -> Highly portable (from one OS to another).
    -> Can run on the limited hardware of that time.

    Limitations:
    -> Large and complex for the hardware of late 1960s and early 1970s.
    -> Computers like PDP-7 had limited memory and processing power making it difficult to run BCPL.
*/


/*
    B Language
    -> B is the stripped-down version of BCPL.
    -> Developed by Ken Thompson in 1969.
    -> Can run on the limited hardware including PDP-7.

    Limitations:
    -> No proper distinction between data types.
    -> Less readable due to lack of constructs like if-else, loops, etc.
    -> Unable to run smoothly on machine like PDP-11.
*/


/*
    C Language
    -> Built on top of B language.
    -> Developed by Dennis Ritchie in 1972.
    -> Data types were introduced with strong type checking.
    -> Structured programming language.
*/