/*
    Features of C Programming:
    1. Efficiency: Efficient because of compliled nature and minimal runtime overhead.

    2. Modularity: Supports modular programming means a program can be divided into smaller, manageable pieces.

    3. Large Standard Library: Large standard library that provides functions for tasks like input/output, string manipulations, mathematical calculations, etc.

    4. Portablility: Can run on different types of computers with little or no modification.

    5. Simple Syntax: Straightforward syntax making it easy to learn and understand.
*/


/*
    Drawbacks of C Programming:
    1. Complexity: Developers are required to manage memory manually, handle pointers carefully, and deal with low level details which can introduce bugs and security vulnerabilities.

    2. Lack of Built-in Features: Lack of features like automatic garbage collection, built-in data structures like dictionaries, and object-oriented programming constructs.

    3. Platform Dependencies: C is portable but still depends on the hardware and the operating system for certain functionalities.

    4. Security risks: Due to low-level nature and lack of built-in safety features, C programs are susceptible to security vulnerabilities such as buffer overflow, memory leaks, etc.
*/