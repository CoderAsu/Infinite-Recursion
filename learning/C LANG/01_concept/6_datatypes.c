/*
    A data type specifies the kind of data a variable can hold.

    Data Types in C:
    1. Primitive
        -> Integer
        -> Character
        -> Float
        -> Void

    2. Derived
        -> Arrays
        -> Pointers
    
    3. User-defined
        -> Structure
        -> Union
        -> Enum
        -> Typedef
*/


/*
    Importance of Data Types:

    1. Memory Allocation: Different data require different amounts of memory. Knowing the data type of a variable helps the compiler allocate the correct amount of memory.

    2. Operations: A data type tells the set of operations that can performed on data.

    3. Type Safety: Using data types ensure only expected data types being manipulated.
*/