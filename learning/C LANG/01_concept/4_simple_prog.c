/*
    int main()
    {
        return 0;
    }
    
    -> here main() is a predefined function and it is a entry point of C program
    -> int represent integer which is a return type of main() function
    -> main() function is called by Operating System
    -> main() function gives an output as an integer to the OS
    -> curly braces represent the body of the main() function.
    -> return 0; is an instruction which is given to the OS to return integer value.
    -> here 0 means successful execution

*/



/*
    User-defined function: functions with functionalities defined by us.
    Pre-defined function: functions with functionalities already defined by someone.
*/

/*
    Header files
    -> files with .h extension
    -> contains function declarations, macros, data types, etc

    syntax to include predefined header files
    #include <filename.h>
*/


/*
    Purpose of predefined header files:
    -> Code Reusability: Developers can rely on predefined functions that are optimized for performance, instead of implementing common functions from scratch.

    -> Error Reduction: Predefined functions are well-tested and hence using these functions reduce the chances of errors in the code.

    -> Documentation and Community Support: Predefined functions comes with thorough documentation and wide community support making the development process easier.
*/


/*
    Commonly Used Header Files:
    -> stdio.h: Provides functions for input and output, such as printf and scanf.
    -> stdlib.h: Provides functions for memory allocation and deallocation (malloc, free), random number generation (rand), etc.
    -> string.h: Provides functions for string mainpulations, such as strlen, strcat, strcpy, etc.
    -> math.h: Provides functions for mathematical operations, such as sqrt, pow, sin, cos, etc.
*/