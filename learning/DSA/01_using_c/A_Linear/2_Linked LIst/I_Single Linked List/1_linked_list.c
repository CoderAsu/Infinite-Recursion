/*
    Linked List

    A linked list is a linear data structure made up of nodes, where each node contains data and a pointer (or reference) to the next node. Unlike arrays, linked lists do not store elements is contiguous memory, making them more flexible for insertion and deletion.

    or

    It is a dynamic linear data structure that stores elements (nodes) connected via pointers.

    Each node has two parts:
    -> Data field: stores the actual value
    -> Pointer field: stores the address of the next node.

    The head node points to the first element, and the last node points to NULL(indicating the end of the list).

    Memory allocation is non-contiguous, unlike arrays.



    Types of Linked Lists
    
    -> Singly Linked List: Each node points only to the next node.
    -> Doubly Linked List: Each node has two pointers - one to the next node and one to the previous node.
    -> Circular Linked List: The last node points back to the head, forming a circle.

    
*/