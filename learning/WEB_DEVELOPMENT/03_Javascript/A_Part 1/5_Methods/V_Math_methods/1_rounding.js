// The Math.abs() method returns the absolute value of a number.

let a = Math.abs(7.25);
let b = Math.abs(-7.25);
let c = Math.abs(null);
let d = Math.abs("Hello");
let e = Math.abs(2-3);

console.log("Math.abs()");

console.log(a);
console.log(b);
console.log(c);
console.log(d);
console.log(e);
















// The Math.ceil() method rounds a number rounded UP to the nearest integer.

let a1 = Math.ceil(0.60);
let b1 = Math.ceil(0.40);
let c1 = Math.ceil(5);
let d1 = Math.ceil(5.1);
let e1 = Math.ceil(-5.1);
let f1 = Math.ceil(-5.9);

console.log("Math.ceil()");

console.log(a1);
console.log(b1);
console.log(c1);
console.log(d1);
console.log(e1);
console.log(f1);
















// The Math.floor() method rounds a number DOWN to the nearest integer.
let a2 = Math.floor(0.60);
let b2 = Math.floor(0.40);
let c2 = Math.floor(5);
let d2 = Math.floor(5.1);
let e2 = Math.floor(-5.1);
let f2 = Math.floor(-5.9);

console.log("Math.floor()");
console.log(a2);
console.log(b2);
console.log(c2);
console.log(d2);
console.log(e2);
console.log(f2);















// The Math.round() method rounds a number to the nearest integer.
// 2.49 will be rounded down (2), and 2.5 will be rounded up (3).

let a3 = Math.round(2.60);
let b3 = Math.round(2.50);
let c3 = Math.round(2.49);
let d3 = Math.round(-2.60);
let e3 = Math.round(-2.50);
let f3 = Math.round(-2.49);

console.log("Math.round()");
console.log(a3);
console.log(b3);
console.log(c3);
console.log(d3);
console.log(e3);
console.log(f3);



















// The Math.fround() function returns the nearest 32-bit single precision float representation of a number.

let a4 = Math.fround(2.60);
let b4 = Math.fround(2.50);
let c4 = Math.fround(2.49);
let d4 = Math.fround(-2.60);
let e4 = Math.fround(-2.50);
let f4 = Math.fround(-2.49);

console.log("Math.fround()");
console.log(a4);
console.log(b4);
console.log(c4);
console.log(d4);
console.log(e4);
console.log(f4);


















// The Math.trunc() method returns the integer part of a number.
// The Math.trunc() method removes the decimals (does NOT round the number).

let a5 = Math.trunc(2.60);
let b5 = Math.trunc(2.50);
let c5 = Math.trunc(2.49);
let d5 = Math.trunc(-2.60);
let e5 = Math.trunc(-2.50);
let f5 = Math.trunc(-2.49);

console.log("Math.trunc()");
console.log(a5);
console.log(b5);
console.log(c5);
console.log(d5);
console.log(e5);
console.log(f5);





















