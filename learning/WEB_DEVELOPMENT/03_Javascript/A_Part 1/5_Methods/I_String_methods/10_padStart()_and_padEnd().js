let text = "5064";

let padded = text.padStart(10, "*");
console.log("+91" + padded);

let text2 = "6372";

let padded2 = text2.padEnd(10, "*");
console.log("+91" + padded2);


// The padStart() method pads a string from the start.

// The padEnd() method pads a string at the end.

// The padStart() and padEnd() method pad a string with another string (multiple times) until it reaches a given length.