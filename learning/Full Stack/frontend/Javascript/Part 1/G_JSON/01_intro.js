// JSON stands for JavaScript Object Notation.
// JSON is a text format for storing and transporting data.
// JSON is "self-description" and easy to understand.
// JSON is language independent.




// Why Use JSON?
// The JSON format is syntactically similar to code for creating JavaScript objects. Because of this, a JavaScript program can easily convert JSON data into JavaScript objects.

// Since the format is text only, JSON data can easily be sent between computers, and used by any programming language.

// JavaScript has a built in function for converting JSON strings into JavaScript objects:
// JSON.parse()

// JavaScript has a built in function for converting an object into a JSON string:
// JSON.stringify()

// You can receive pure text from a server and use it as a JavaScript object.

// You can send a JavaScript object to a server in pure text format.












// JSON Syntax Rules
/* 
    JSON syntax is derived from JavaScript object notation syntax:
    => Data is in name/value pairs
    => Data is separated by commas
    => Curly braces hold objects
    => Square brackets hold arrays
*/





// Valid Data Types
/* 
    In JSON, values must be one of the following data types:
    => a string
    => a number
    => an object
    => an array
    => a boolean
    => null
*/
/* 
    JSON values cannot be one of the following types:
    => a function
    => a date
    => undefined
*/