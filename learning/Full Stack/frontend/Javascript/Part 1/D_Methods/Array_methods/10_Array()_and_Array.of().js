// Using Array() with a single number creates an array with that length.

const arr = Array(5);
console.log(arr);




// Whereas, Array.of() creates an array containing that number as an element.

const arr2 = Array.of(5);
console.log(arr2);




const arr3 = Array(1, 2, 3, 4, 5);
console.log(arr3);


const arr4 = Array.of(6, 7, 8, 9, 10);
console.log(arr4);




// The Array.of() method creates a new array from any number of arguments.

// The Array.of() method can take any type of arguments.