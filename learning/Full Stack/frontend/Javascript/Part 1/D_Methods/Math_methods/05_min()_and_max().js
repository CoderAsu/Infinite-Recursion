// The Math.min() method returns the number with the lowest value.

let a = Math.min(5, 10);
let b = Math.min(0, 150, 30, 20, 38);
let c = Math.min(-5, 10);
let d = Math.min(-5, -10);
let e = Math.min(1.5, 2.5);

console.log(a);
console.log(b);
console.log(c);
console.log(d);
console.log(e);










// The Math.max() method returns the number with the highest value.

let f = Math.max(5, 10);
